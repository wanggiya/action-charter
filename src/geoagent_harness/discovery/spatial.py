"""Metadata-only local TIFF/GPKG/Shapefile discovery over a closed FD package.

GDAL sees only private aliases to already opened regular files. Whole-package
hashing streams bytes; metadata availability is not geometric validation.
"""
from __future__ import annotations
from contextlib import ExitStack, contextmanager
import hashlib
import json
import math
import os
from pathlib import Path
import stat
from tempfile import TemporaryDirectory
import time

from .source import _parent, relative_path
from .csv import identity

MAX_BYTES=1024**3
MAX_SECONDS=120
SUFFIXES={'.tif','.tiff','.gpkg','.shp'}


def _entries(parent):
    names=[]
    with os.scandir(parent) as entries:
        for entry in entries:
            names.append(entry.name)
            if len(names)>10000:raise ValueError('Input directory exceeds discovery budget')
    return names


@contextmanager
def package(root,path):
    path=relative_path(path,'input')
    suffix=Path(path).suffix.lower()
    if suffix not in SUFFIXES:raise ValueError('Unsupported metadata discovery format')
    with ExitStack() as stack:
        parent,name=_parent(stack,root,path)
        names=_entries(parent)
        stem=Path(name).stem
        members=[name]
        if suffix=='.shp':
            members=[stem+ext for ext in ('.shp','.shx','.dbf')]
            members += [stem+ext for ext in ('.prj','.cpg') if stem+ext in names]
            if any(item.lower().startswith(stem.lower()+'.') and item not in members for item in names):
                raise ValueError('Shapefile requires a closed lowercase shp/shx/dbf/prj/cpg package')
        elif suffix in {'.tif','.tiff'}:
            if any((item.lower().startswith(stem.lower()+'.') and item!=name) for item in names):
                raise ValueError('External TIFF sidecars are unsupported')
        elif any(name+ext in names for ext in ('-wal','-shm','-journal')):
            raise ValueError('Active GeoPackage journals are unsupported')
        files={};total=0
        for member in members:
            fd=os.open(member,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK,dir_fd=parent)
            stack.callback(os.close,fd)
            info=os.fstat(fd)
            if not stat.S_ISREG(info.st_mode):raise ValueError('Discovery requires regular files')
            total+=info.st_size
            if total>MAX_BYTES:raise ValueError('Spatial package exceeds 1 GiB')
            files[str(Path(path).with_name(member))]=(fd,identity(info))
        header=os.pread(files[path][0],16,0)
        valid=(header==b'SQLite format 3\x00' if suffix=='.gpkg' else
               header[:4]==b'\x00\x00\x27\x0a' if suffix=='.shp' else
               header[:4] in (b'II*\x00',b'MM\x00*',b'II+\x00',b'MM\x00+'))
        if not valid:raise ValueError('Source signature does not match its declared format')
        if suffix=='.gpkg' and os.pread(files[path][0],2,18)!=b'\x01\x01':
            raise ValueError('WAL-mode GeoPackage files require a closed checkpointed source')
        yield path,files,total


def unchanged(root,path,files):
    if any(identity(os.fstat(fd))!=before for fd,before in files.values()):
        raise ValueError('Spatial source changed during discovery')
    with package(root,path) as (_,current,_):
        if {name:info for name,(_,info) in current.items()}!={name:info for name,(_,info) in files.items()}:
            raise ValueError('Spatial package or pathname changed during discovery')


def finite(values):
    result=[float(value) for value in values]
    return result if all(math.isfinite(value) for value in result) else None


def metadata(path,files,total):
    suffix=Path(path).suffix.lower()
    # These aliases are generated by trusted code, not supplied by the caller.
    with TemporaryDirectory(prefix='actioncharter-metadata-',dir='/tmp') as directory:
        folder=Path(directory)
        for name,(fd,_) in files.items():
            (folder/Path(name).name).symlink_to(f'/proc/self/fd/{fd}')
        local=folder/Path(path).name
        if suffix in {'.tif','.tiff'}:
            import rasterio
            with rasterio.Env(GDAL_DISABLE_READDIR_ON_OPEN='EMPTY_DIR',GDAL_PAM_ENABLED='NO',PROJ_NETWORK='OFF'):
                with rasterio.open(local,driver='GTiff') as raster:
                    if raster.count>128:raise ValueError('Raster metadata exceeds 128 bands')
                    bounds=finite(raster.bounds);transform=finite(tuple(raster.transform)[:6])
                    if bounds is None or transform is None:raise ValueError('Nonfinite raster georeferencing')
                    encodings=[None if value is None else 'NaN' if math.isnan(value) else str(value) if not math.isfinite(value) else None for value in raster.nodatavals]
                    result={'operation':'inspect_raster','driver':'GTiff','width':raster.width,'height':raster.height,
                        'band_count':raster.count,'data_types':list(raster.dtypes),
                        'crs':raster.crs.to_string() if raster.crs else None,
                        'bounds':dict(zip(('left','bottom','right','top'),bounds)),
                        'transform':transform,'resolution':finite(raster.res),
                        'nodata_values':[None if value is None or not math.isfinite(value) else value for value in raster.nodatavals],
                        'nodata_encodings':encodings,'overviews':raster.overviews(1)[:16]}
                    from .raster_metadata import technical_metadata
                    result['technical_details']=technical_metadata(raster)
        else:
            import pyogrio
            expected='GPKG' if suffix=='.gpkg' else 'ESRI Shapefile'
            layers=pyogrio.list_layers(local)
            if not 0<len(layers)<=8:raise ValueError('Vector metadata requires 1–8 layers')
            items=[]
            for name,_ in layers:
                info=pyogrio.read_info(local,layer=str(name),force_feature_count=False,force_total_bounds=False)
                if info['driver']!=expected:raise ValueError('Unexpected vector driver')
                count=int(info['features']);bounds=finite(info['total_bounds']) if info['total_bounds'] is not None else None
                crs=info['crs']
                if crs is not None and len(crs)>1024:raise ValueError('CRS metadata exceeds output budget')
                if len(str(name))>120:raise ValueError('Layer name exceeds metadata budget')
                fields=[{'name':str(field)[:200],'type':str(dtype)[:60]} for field,dtype in zip(info['fields'][:100],info['dtypes'][:100])]
                items.append({'name':str(name),'crs':crs,'geometry_type':info['geometry_type'] or 'None',
                    'feature_count':count if count>=0 else None,
                    'feature_count_basis':'driver_available_metadata' if count>=0 else 'not_computed_expensive',
                    'fields':fields,'field_count':len(info['fields']),'fields_truncated':len(info['fields'])>100,
                    'extent':dict(zip(('min_x','min_y','max_x','max_y'),bounds)) if bounds else None,
                    'extent_basis':'driver_available_metadata' if bounds else 'not_computed_or_unavailable'})
            result={'operation':'inspect_vector','driver':expected,'layers':items}
    result.update(source=path,effects='read_only',execution_performed=True,validation_performed=False,
        filesystem_modified=False,database_modified=False,
        discovery={'schema_version':'spatial-discovery-v1','phase':'verifying','verification':'pending',
                   'statistics_scope':'driver_metadata_only','file_bytes':total,'file_count':len(files),
                   'display_scope':'existing_bounded_spatial_views'},
        warnings=['Characteristics are driver metadata, not a full geometry/pixel validation or newly computed statistics.',
                  'Full package SHA-256 is pending. No pixels or feature frames are materialized for this inspection.'])
    # Preserve counts/identity rather than losing the whole result to wide schemas.
    while len(json.dumps(result).encode())>14000:
        layer=max(result.get('layers',[]),key=lambda item:len(item['fields']),default=None)
        if layer is None or not layer['fields']:raise ValueError('Spatial metadata exceeds output budget')
        layer['fields'].pop();layer['fields_truncated']=True
    return result


def probe(root,path):
    with package(root,path) as (path,files,total):
        value=metadata(path,files,total)
        unchanged(root,path,files)
        return {'path':path,'bytes':total,'source_identity':{name:before for name,(_,before) in files.items()},
                'discovery_kind':'streaming_spatial_v1','metadata':value}


def inspect(root,path,*,expected_identity=None,on_metadata=None,checkpoint=None):
    deadline=time.monotonic()+MAX_SECONDS
    with package(root,path) as (path,files,total):
        before={name:info for name,(_,info) in files.items()}
        if expected_identity is not None and before!=expected_identity:
            raise ValueError('Spatial source changed since submission')
        result=metadata(path,files,total)
        unchanged(root,path,files)
        if on_metadata:on_metadata(json.loads(json.dumps(result,allow_nan=False)))
        hashes={}
        for name,(fd,_) in files.items():
            digest=hashlib.sha256();os.lseek(fd,0,os.SEEK_SET)
            while True:
                if checkpoint:checkpoint()
                if time.monotonic()>deadline:raise ValueError('Spatial discovery exceeded its deadline')
                chunk=os.read(fd,65536)
                if not chunk:break
                digest.update(chunk)
            hashes[name]=digest.hexdigest()
        unchanged(root,path,files)
        result['source_sha256']=hashlib.sha256(json.dumps(hashes,sort_keys=True).encode()).hexdigest()
        result['source_manifest']=hashes
        result['discovery'].update(phase='completed',verification='sha256_complete',bytes_hashed=total,
            consistency='opened-file and pathname stat checks; not an immutable snapshot')
        result['warnings']=['Driver metadata only; counts/extents can be cached, unavailable or stale. Hash completion does not validate geometries or pixels.',
                            'Processing and spatial display retain their separate limits.']
        from .spatial_contracts import RasterMetadata,VectorMetadata
        (RasterMetadata if result['operation']=='inspect_raster' else VectorMetadata).model_validate(result)
        return result
