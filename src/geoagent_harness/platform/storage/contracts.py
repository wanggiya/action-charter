"""Transport-independent storage contracts; no SQL or executable entry points."""
from contextlib import AbstractContextManager
from dataclasses import dataclass
from pathlib import Path
from typing import Literal, Protocol, TYPE_CHECKING, overload

if TYPE_CHECKING:
    from geoagent_harness.contracts.planning import PlannerResult

Collection = Literal['conversations', 'tasks', 'memories', 'inspection_submissions_v1',
    'chat_history_blobs_v1', 'chat_history_v1', 'method_memory_records',
    'dataset_views_v1', 'capability_attempts', 'request_diagnostics_v1']
Setting = Literal['model_selection', 'model_reasoning_selection', 'outcome_review_settings',
    'method_memory_settings', 'method_helper_settings']


class RepositoryError(RuntimeError):
    """A storage contract could not be fulfilled; never permission to replay."""


@dataclass(frozen=True)
class Record:
    key: str
    content: str
    owner: str | None = None
    kind: str | None = None
    parent: str | None = None


class Records(Protocol):
    def available(self) -> bool: ...
    def ensure(self) -> None: ...
    def get(self, key: str) -> str | None: ...
    def entries(self, *, owner: str | None = None, limit: int | None = None) -> list[Record]: ...
    def count(self, *, owner: str | None = None) -> int: ...
    def put(self, key: str, content: str, *, owner: str | None = None,
            kind: str | None = None, parent: str | None = None, ignore_existing: bool = False) -> None: ...
    def delete(self, key: str, *, owner: str | None = None) -> None: ...


class MetadataTransaction(Protocol):
    def records(self, collection: Collection) -> Records: ...
    def setting(self, name: Setting) -> dict | None: ...
    def save_setting(self, name: Setting, value: object, revision: int) -> None: ...
    def prune_diagnostics(self, *, turns: int, calls: int) -> None: ...
    def recent_diagnostic_chats(self) -> list[str]: ...
    def helper_note(self, owner: str, key: str) -> str | None: ...
    def save_helper_note(self, owner: str, key: str, content: str, *, per_chat: int, per_project: int) -> None: ...


class JsonRecords(Protocol):
    directory: Path
    def ensure(self) -> Path: ...
    def read(self, name: str) -> dict: ...
    def create(self, name: str, content: str) -> None: ...
    def replace(self, name: str, content: str) -> None: ...
    def names(self, *, order: Literal['name', 'recent', 'native'] = 'name', limit: int | None = None) -> list[str]: ...


class SavedPlans(JsonRecords, Protocol):
    def load(self, name: str) -> 'PlannerResult': ...


class WorkspaceRepositories(Protocol):
    project_root: Path
    def transaction(self, *, write: bool = False) -> AbstractContextManager[MetadataTransaction | None]: ...
    def runs(self, *, directory: Path | None = None) -> JsonRecords: ...
    @overload
    def documents(self, store: Literal['plans'], *, directory: Path | None = None) -> SavedPlans: ...
    @overload
    def documents(self, store: Literal['planner-conversations'], *, directory: Path | None = None) -> JsonRecords: ...
