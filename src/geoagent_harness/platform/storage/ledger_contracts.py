"""Specialized persistence ports; none of these methods grants execution authority."""
from contextlib import AbstractContextManager
from pathlib import Path
from typing import Callable, Protocol, TextIO


class LedgerStorageError(OSError):
    """Storage failed or is uncertain; never a signal to replay an operation."""


class UnsafeLedgerRecord(LedgerStorageError):
    """A local immutable record failed its file-type/link/size contract."""


class ImmutableRecords(Protocol):
    def create_text(self, name: str, *, encoding: str = 'utf-8', newline: str | None = None) -> AbstractContextManager[TextIO]: ...
    def read_text(self, name: str, *, encoding: str = 'utf-8') -> str: ...
    def read_bytes(self, name: str, *, max_bytes: int) -> bytes: ...
    def publish_directory(self, staged: Path, name: str, *, rename: bool = False) -> None: ...
    def publish_file(self, staged: Path, name: str) -> None: ...


class AttemptLedger(Protocol):
    def lock(self, name: str) -> AbstractContextManager[None]: ...
    def claim(self, name: str, content: bytes) -> None: ...
    def append(self, name: str, content: Callable[[], bytes], *, create: bool, max_existing_bytes: int) -> None: ...
    def replace_snapshot(self, name: str, content: bytes) -> None: ...
    def sync(self) -> None: ...
    def append_checked(self, name: str, content: Callable[[bytes], bytes], *, max_bytes: int) -> None: ...


class WritePolicyStore(Protocol):
    def current(self) -> dict | None: ...
    def initialize(self, identity: str, enabled: bool, locked: bool) -> None: ...
    def begin_write(self) -> None: ...
    def set_enabled(self, enabled: bool) -> None: ...
    def record_change(self, session: str, revision: int, enabled: bool, event: str) -> None: ...
    def bind(self, digest: str, session: str, revision: int) -> None: ...
    def approval_scope(self, digest: str) -> tuple[str, int] | None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...


class SuccessfulMethods(Protocol):
    def __enter__(self) -> 'SuccessfulMethods': ...
    def __exit__(self, kind, value, traceback) -> bool | None: ...
    def begin_write(self) -> None: ...
    def success(self, identity: str) -> tuple[str, str | None] | None: ...
    def count(self) -> int: ...
    def insert(self, identity: str, method: str, owner: str | None, content: str) -> None: ...
    def entries(self, owner: str | None, limit: int) -> list[tuple[str]]: ...
    def annotations(self, owner: str | None) -> list[tuple[str, str]]: ...
    def save_annotation(self, identity: str, content: str) -> None: ...
    def close(self) -> None: ...


class LedgerRepositories(Protocol):
    def immutable(self, directory: Path) -> ImmutableRecords: ...
    def attempts(self, directory: Path) -> AttemptLedger: ...
    def write_policy(self, database: Path) -> AbstractContextManager[WritePolicyStore]: ...
    def successes(self, project_root: Path) -> SuccessfulMethods: ...
